// Checklist строит чек-лист ручной настройки новой машины из списка «не синхронизируется».
func Checklist(sections []NotSyncedSection, manual []ManualItem) string {
	var b strings.Builder
	b.WriteString("# Чек-лист ручной настройки новой машины\n\n")
	b.WriteString("Это то, что EnvSync не переносит сам. Пройдите по пунктам после первого запуска.\n")
	for _, s := range sections {
		fmt.Fprintf(&b, "\n## %s\n\n", s.Title)
		for _, it := range s.Items {
			fmt.Fprintf(&b, "- [ ] %s: %s.\n", it.What, strings.TrimSuffix(it.Workaround, "."))
		}
	}
	if len(manual) > 0 {
		b.WriteString("\n## Программы, которые ставятся вручную\n\n")
		for _, m := range manual {
			fmt.Fprintf(&b, "- [ ] %s %s\n", m.Name, m.Note)
		}
	}
	return b.String()
}
